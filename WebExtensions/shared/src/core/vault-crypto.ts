/**
 * Vault crypto chain (WebCrypto), byte-for-byte compatible with the Swift
 * `DatabaseCipher` container formats — see Core/DatabaseCipher.swift layout:
 *
 * envelope (UPWKEY1\0):
 *   [0..8) magic, [8..12) version u32 LE, [12..16) PBKDF2 iterations u32 LE,
 *   [16..32) salt, [32..92) AES-GCM combined (nonce 12 + ct 32 + tag 16)
 *   wrapping the 32-byte vault key, [92..100) changedAt f64 LE.
 *
 * body (UPWDB2\0\0):
 *   [0..8) magic, [8..12) version u32 LE, [12..16) flags u32 LE,
 *   [16..) AES-GCM combined (nonce 12 + ct + tag 16) with the vault key.
 *
 * Cross-platform parity is enforced by shared/test/vault-crypto.test.mjs
 * against a fixture generated by the Swift side (real bytes, real KDF).
 */

import type { ExtensionItem } from "./types.js";

const ENVELOPE_MAGIC = [0x55, 0x50, 0x57, 0x4b, 0x45, 0x59, 0x31, 0x00];
const BODY_MAGIC = [0x55, 0x50, 0x57, 0x44, 0x42, 0x32, 0x00, 0x00];

export class VaultCryptoError extends Error {
    constructor(message: string) {
        super(message);
        this.name = "VaultCryptoError";
    }
}

function hasMagic(bytes: Uint8Array, magic: number[]): boolean {
    if (bytes.length < magic.length) return false;
    return magic.every((byte, i) => bytes[i] === byte);
}

function u32LE(bytes: Uint8Array, offset: number): number {
    return (bytes[offset] | (bytes[offset + 1] << 8) | (bytes[offset + 2] << 16) | (bytes[offset + 3] << 24)) >>> 0;
}

/** PBKDF2-SHA256(password, salt, iterations) → 32 bytes, mirrors deriveKey(). */
async function deriveKeyBytes(password: string, salt: Uint8Array, iterations: number): Promise<Uint8Array> {
    const passwordBytes = new TextEncoder().encode(password);
    let material: CryptoKey;
    try {
        material = await crypto.subtle.importKey("raw", passwordBytes, "PBKDF2", false, ["deriveBits"]);
    } finally {
        passwordBytes.fill(0);
    }
    const bits = await crypto.subtle.deriveBits(
        { name: "PBKDF2", hash: "SHA-256", salt: salt as BufferSource, iterations },
        material,
        256,
    );
    return new Uint8Array(bits);
}

/**
 * Unwrap the key envelope with the master password; returns the raw 32-byte
 * vault key. Throws VaultCryptoError("wrong_password") on any mismatch.
 */
export async function unwrapEnvelope(envelope: Uint8Array, password: string): Promise<Uint8Array> {
    if (envelope.length < 92 || !hasMagic(envelope, ENVELOPE_MAGIC)) {
        throw new VaultCryptoError("not_a_key_envelope");
    }
    const iterations = u32LE(envelope, 12);
    // 下限与 Swift DatabaseCipher.minimumEnvelopeIterations 对齐:伪造低迭代
    // 信封按坏文件拒绝,不给降级/误导面
    if (iterations < 100_000 || iterations > 10_000_000) {
        throw new VaultCryptoError("bad_iterations");
    }
    const salt = envelope.slice(16, 32);
    const keyBytes = await deriveKeyBytes(password, salt, iterations);
    // combined = nonce(12) + ct(32) + tag(16); WebCrypto takes ct||tag with the nonce as iv
    try {
        const key = await importVaultDecryptKey(keyBytes);
        const plain = await crypto.subtle.decrypt(
            { name: "AES-GCM", iv: envelope.slice(32, 44) as BufferSource },
            key,
            envelope.slice(44, 92) as BufferSource,
        );
        return new Uint8Array(plain);
    } catch {
        throw new VaultCryptoError("wrong_password");
    } finally {
        keyBytes.fill(0);
    }
}

/** Decrypt the database body with the vault key; returns the XML text. */
export async function decryptBody(body: Uint8Array, vaultKey: Uint8Array): Promise<string> {
    if (body.length < 32 || !hasMagic(body, BODY_MAGIC)) {
        throw new VaultCryptoError("not_a_v2_container");
    }
    const key = await crypto.subtle.importKey("raw", vaultKey as BufferSource, "AES-GCM", false, ["decrypt"]);
    try {
        const plain = await crypto.subtle.decrypt(
            { name: "AES-GCM", iv: body.slice(16, 28) as BufferSource },
            key,
            body.slice(28) as BufferSource,
        );
        return new TextDecoder().decode(plain);
    } catch {
        throw new VaultCryptoError("vault_key_mismatch");
    }
}

/**
 * Wrap a fresh vault key with the master password (vault creation from the
 * extension). Mirrors Swift `DatabaseCipher.wrapVaultKey` byte layout:
 * magic(8) + version u32 + iterations u32 + salt(16) + GCM(nonce12+ct32+tag16)
 * + changedAt f64 (epoch SECONDS). Returns the envelope and the raw 32-byte
 * vault key (caller must not persist the key).
 */
export async function wrapEnvelope(password: string, iterations = 600_000): Promise<{ envelope: Uint8Array; vek: Uint8Array }> {
    const vek = crypto.getRandomValues(new Uint8Array(32));
    const salt = crypto.getRandomValues(new Uint8Array(16));
    const kek = await deriveKeyBytes(password, salt, iterations);
    try {
        const wrapKey = await crypto.subtle.importKey("raw", kek as BufferSource, "AES-GCM", false, ["encrypt"]);
        const nonce = crypto.getRandomValues(new Uint8Array(12));
        const sealed = new Uint8Array(await crypto.subtle.encrypt({ name: "AES-GCM", iv: nonce }, wrapKey, vek));
        const envelope = new Uint8Array(100);
        envelope.set(ENVELOPE_MAGIC, 0);
        const view = new DataView(envelope.buffer);
        view.setUint32(8, 1, true);
        view.setUint32(12, iterations, true);
        envelope.set(salt, 16);
        envelope.set(nonce, 32);
        envelope.set(sealed, 44);
        view.setFloat64(92, Date.now() / 1000, true);
        return { envelope, vek };
    } catch (error) {
        vek.fill(0);
        throw error;
    } finally {
        kek.fill(0);
    }
}

/** changedAt recorded in the envelope (password-change propagation hint). */
export function envelopeChangedAt(envelope: Uint8Array): number | null {
    if (envelope.length < 100 || !hasMagic(envelope, ENVELOPE_MAGIC)) return null;
    const view = new DataView(envelope.buffer, envelope.byteOffset + 92, 8);
    return view.getFloat64(0, true);
}

/**
 * Decrypt one row-sync item body (v7 §6.2): AES-GCM(vaultKey) combined
 * (nonce 12 + ct + tag), AAD bound to the item uuid. Mirrors Swift
 * `RowSyncCipher` byte-for-byte — the AAD is the *uppercase* canonical
 * uuid string (Swift uuidString); the server normalizes stored uuids to
 * lowercase, so callers must pass the server uuid and we re-uppercase here.
 * Throws VaultCryptoError("item_decrypt_failed") on mismatch.
 */
export async function decryptItemBody(body: Uint8Array, vaultKey: Uint8Array, uuid: string): Promise<string> {
    try {
        return await decryptItemBodyWithKey(body, await importVaultDecryptKey(vaultKey), uuid);
    } catch {
        throw new VaultCryptoError("item_decrypt_failed");
    }
}

/** Import once per batch; the decrypt-only AES-256 key cannot be exported. */
export async function importVaultDecryptKey(vaultKey: Uint8Array): Promise<CryptoKey> {
    if (vaultKey.length !== 32) throw new VaultCryptoError("invalid_vault_key");
    return crypto.subtle.importKey("raw", vaultKey as BufferSource, "AES-GCM", false, ["decrypt"]);
}

/** Decrypt one row with a previously imported key, preserving UUID AAD binding. */
export async function decryptItemBodyWithKey(body: Uint8Array, key: CryptoKey, uuid: string): Promise<string> {
    if (body.length < 28 || !uuid) throw new VaultCryptoError("item_decrypt_failed");
    let plain: Uint8Array | undefined;
    try {
        plain = new Uint8Array(await crypto.subtle.decrypt(
            {
                name: "AES-GCM",
                iv: body.slice(0, 12) as BufferSource,
                additionalData: new TextEncoder().encode(uuid.toUpperCase()) as BufferSource,
            },
            key,
            body.slice(12) as BufferSource,
        ));
        return new TextDecoder("utf-8", { fatal: true }).decode(plain);
    } catch {
        throw new VaultCryptoError("item_decrypt_failed");
    } finally {
        plain?.fill(0);
    }
}

/**
 * Encrypt a row-sync fragment with a fresh 12-byte nonce and the uppercase canonical UUID as AAD.
 * Output is nonce || ciphertext || 16-byte tag, matching decryptItemBody and Swift RowSyncCipher.
 * The caller owns reauthentication and clearing the raw vault key; this helper never persists it.
 */
export async function encryptItemBody(xml: string, vaultKey: Uint8Array, uuid: string): Promise<Uint8Array> {
    const canonicalUuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
    if (!canonicalUuid.test(uuid) || vaultKey.length !== 32) {
        throw new VaultCryptoError("item_encrypt_failed");
    }
    try {
        const key = await crypto.subtle.importKey("raw", vaultKey as BufferSource, "AES-GCM", false, ["encrypt"]);
        const nonce = crypto.getRandomValues(new Uint8Array(12));
        const sealed = new Uint8Array(await crypto.subtle.encrypt(
            {
                name: "AES-GCM",
                iv: nonce,
                additionalData: new TextEncoder().encode(uuid.toUpperCase()),
            },
            key,
            new TextEncoder().encode(xml),
        ));
        const body = new Uint8Array(nonce.length + sealed.length);
        body.set(nonce);
        body.set(sealed, nonce.length);
        return body;
    } catch {
        throw new VaultCryptoError("item_encrypt_failed");
    }
}

/**
 * Concatenate decrypted item fragments (each a standalone `<card>`/`<label>`
 * element, exactly what Swift `DatabaseItemCodec.xmlData` produces) into a
 * document `parseVaultXml` can read; label elements are ignored by the parser.
 */
export function fragmentsToXml(fragments: string[]): string {
    return `<passworddatabase>${fragments.join("")}</passworddatabase>`;
}

/** XML 属性来自不可信输入:白名单外的值回退默认,禁止 as 断言直接放行。 */
const FIELD_TYPES: ReadonlySet<string> = new Set([
    "login", "password", "pin", "number", "date", "phone",
    "website", "email", "one_time_password", "text", "expiry", "secret",
]);
const AUTOFILL_TOKENS: ReadonlySet<string> = new Set([
    "off", "username", "current-password", "url", "one-time-code",
    "cc-number", "cc-name", "cc-exp", "cc-csc",
]);

/**
 * Parse the vault XML into fill items. Mirrors the native handler filter
 * (skip trashed/archived/template cards); DOMParser is required, so call
 * this from the popup page context, not from a worker without DOM.
 */
export function parseVaultXml(xml: string): ExtensionItem[] {
    if (typeof DOMParser === "undefined") {
        throw new VaultCryptoError("dom_unavailable");
    }
    const doc = new DOMParser().parseFromString(xml, "application/xml");
    if (doc.querySelector("parsererror")) {
        throw new VaultCryptoError("bad_xml");
    }
    const items: ExtensionItem[] = [];
    for (const card of Array.from(doc.querySelectorAll("card"))) {
        if (card.getAttribute("trashed") === "true" || card.getAttribute("archived") === "true" || card.getAttribute("template") === "true") {
            continue;
        }
        // Keep opaque future subtrees out of the editable field projection, matching item-editor.
        const directFields = Array.from(card.children).filter((element) => element.tagName === "field" && !element.namespaceURI);
        const fields = directFields.map((field) => {
            const type = field.getAttribute("type") ?? "text";
            const autofill = field.getAttribute("autofill") ?? "off";
            return {
                name: field.getAttribute("name") ?? "",
                type: (FIELD_TYPES.has(type) ? type : "text") as ExtensionItem["fields"][number]["type"],
                value: field.textContent ?? "",
                autofill: (AUTOFILL_TOKENS.has(autofill) ? autofill : "off") as ExtensionItem["fields"][number]["autofill"],
            };
        });
        const website = fields.find((f) => f.type === "website")?.value ?? "";
        // v7 条目 id 为 UUID 字符串;缺 id 用空串,变更检测按指纹失真可见
        items.push({
            id: card.getAttribute("id") ?? "",
            title: card.getAttribute("title") ?? "",
            symbol: card.getAttribute("symbol"),
            fields,
            host: website.trim(),
        });
    }
    return items;
}
